"""Generate ``data/music_log_catalog.py`` from Darkan's period song table.

Source, top of the project's evidence order:
``darkan-world-server/data/music/songs.json`` — the Nov-2012 song table, one
row per track with the period ``name`` and the period ``hint`` describing how
the track is unlocked. Darkan itself unlocks tracks by map region and has no
achievement hook at all, so the hint text is the only machine-readable unlock
statement the source carries.

The translation rule, and the abstraction it makes explicit:

AnkiScape has no map, so a hint that names a *place* cannot become a predicate.
A track is kept only when its hint names something AnkiScape can prove from
durable state — a quest we ship, or a completed-task count. Every other track
is dropped rather than given an invented trigger. That keeps the log's
denominator honest: the Completionist music requirement counts exactly the
tracks a player can actually reach.

Run:

    python3 tools/harvest_music_log.py
"""

from __future__ import annotations

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pkg_alias  # noqa: E402,F401

from ankiscape.data.quest_data import QUESTS  # noqa: E402

SONGS_JSON = (
    "/Users/ArmanTarkhanian1/Documents/2012scape with bots/darkan-world-server"
    "/data/music/songs.json"
)
DARKAN_COMMIT = "c95aca409f397cab12c13b6d5269b73f6cd8abe9"
OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data",
    "music_log_catalog.py",
)

# Only these openings state a completion or participation, rather than a place.
COMPLETION_HINT = re.compile(
    r"^(during|on completion of|on completing|after completing|upon completing|by completing)\b"
)

# The one achievement-milestone track, and the only row Darkan states outright:
# songs.json id 941, hint "by completing 350 Tasks."
TASK_TRACK_ID = 941


def _quest_trigger(hint: str) -> str:
    lowered = hint.lower()
    for quest in sorted(QUESTS, key=lambda q: -len(q.display_name)):
        if quest.display_name.lower() in lowered:
            return quest.id
    return ""


def build() -> str:
    songs = json.load(open(SONGS_JSON, encoding="utf-8"))
    rows: list[str] = []
    kept = 0
    for song in sorted(songs, key=lambda s: int(s["id"])):
        hint = str(song.get("hint", "")).strip()
        name = str(song.get("name", "")).strip()
        if not name or not COMPLETION_HINT.match(hint.lower()):
            continue
        if int(song["id"]) == TASK_TRACK_ID:
            kind, key = "task_count", ""
        else:
            quest_id = _quest_trigger(hint)
            if not quest_id:
                continue
            kind, key = "quest", quest_id
        kept += 1
        rows.append(
            "    MusicTrack(%d, %r, %r, %r, %r),"
            % (int(song["id"]), name, hint, kind, key)
        )
    body = "\n".join(rows)
    return (
        '"""Generated by ``tools/harvest_music_log.py``. Do not hand-edit.\n\n'
        "Source: darkan-world-server %s data/music/songs.json — the period song\n"
        "table's own ``name`` and ``hint`` columns. See the generator's module\n"
        "docstring for the translation rule and for the abstraction it makes\n"
        "explicit.\n\nTracks kept: %d.\n\"\"\"\n\n"
        "from __future__ import annotations\n\n"
        "from .music_log_data import MusicTrack\n\n\n"
        "MUSIC_TRACKS: tuple[MusicTrack, ...] = (\n%s\n)\n"
    ) % (DARKAN_COMMIT, kept, body)


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(build())
    print(f"wrote {OUT}")
